/**
 * dsh-mattpocock-skills — Matt Pocock's skills, verbatim, for the DeepSeek
 * Harness.
 *
 * This module is a Cordis plugin. It registers exactly one skill provider on
 * `ctx.skills`, in the host layer, so every agent preset's scope chain merges
 * the skills it publishes.
 *
 * What "verbatim" means here, and why it is the whole design:
 *   - `skills/<name>/` holds the upstream files byte for byte, including the
 *     `SKILL.md` body and every relative reference it names
 *     (`PHASE-BOUNDARIES.md`, `DEEPENING.md`, `agents/openai.yaml`, ...).
 *   - No prose is rewritten, no slash-command prefix is stripped, no step is
 *     dropped. Upstream is a Claude Code plugin; DSH consumes the same
 *     `SKILL.md` format, so fidelity is achievable and any edit would silently
 *     diverge from the skill Matt Pocock documents.
 *   - `catalog.json` is generated by `scripts/sync-upstream.mjs` from the
 *     upstream plugin manifest. It carries the parsed frontmatter plus a
 *     SHA-256 for every shipped file, so `npm run verify` can prove the bytes
 *     still match what was synced. Discovery therefore never re-parses YAML at
 *     runtime: this package has zero runtime dependencies.
 *
 * Precedence: `rank` is 350. Lower wins within a layer. That puts these skills
 * above stale copies in `~/.dsh/skills` (400) and `~/.agents/skills` (500) — a
 * packaged plugin should not lose to an old checkout of the same skills — while
 * still letting a project's own `.dsh/skills` (100) or `.agents/skills` (200)
 * override any of them.
 *
 * @module dsh-mattpocock-skills
 */
import { readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const name = 'dsh-mattpocock-skills'
const inject = ['skills']

/** Registry precedence for a packaged skill provider (see the note above). */
const PACKAGE_RANK = 350

/** The source bucket these skills advertise under (prompt-visible metadata). */
const SOURCE = 'bundled-mattpocock'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG_PATH = join(ROOT, 'catalog.json')
const SKILLS_ROOT = join(ROOT, 'skills')

/** Parsed `catalog.json`, read once per process. */
let catalogPromise

/**
 * Load the generated catalog.
 * @returns the parsed catalog, whose `skills` array mirrors the upstream
 *   plugin manifest order.
 */
function loadCatalog() {
  catalogPromise ??= readFile(CATALOG_PATH, 'utf8').then((text) => JSON.parse(text))
  return catalogPromise
}

/**
 * Return the Markdown body of a `SKILL.md`, using the same delimiter rules as
 * `@deepseek-ai/dsh-skill-filesystem` so the model sees the same text either
 * way: the file opens with a `---` line, the block ends at the next `---` line
 * on its own, and the body is trimmed.
 * @param raw - the whole file.
 * @returns the trimmed body, or undefined when the frontmatter is malformed.
 */
function bodyOf(raw) {
  const firstLineEnd = raw.indexOf('\n')
  if (firstLineEnd < 0) return undefined
  if (raw.slice(0, firstLineEnd).replace(/\r$/, '') !== '---') return undefined
  let lineStart = firstLineEnd + 1
  while (lineStart <= raw.length) {
    const nextNewline = raw.indexOf('\n', lineStart)
    const lineEnd = nextNewline < 0 ? raw.length : nextNewline
    if (raw.slice(lineStart, lineEnd).replace(/\r$/, '') === '---') {
      return raw.slice(nextNewline < 0 ? raw.length : nextNewline + 1).trim()
    }
    if (nextNewline < 0) return undefined
    lineStart = nextNewline + 1
  }
  return undefined
}

/**
 * Build the discovery candidate for one catalog entry. The locator is this
 * provider's own opaque handle: the reading half of `get()` only needs the
 * skill directory and the file path.
 * @param skill - one entry from `catalog.json`.
 */
function candidateFor(skill) {
  const directory = join(SKILLS_ROOT, skill.name)
  const path = join(directory, 'SKILL.md')
  return {
    name: skill.name,
    description: skill.description,
    ...(skill.whenToUse !== undefined ? { whenToUse: skill.whenToUse } : {}),
    invocation: skill.invocation,
    source: SOURCE,
    provider: name,
    rank: PACKAGE_RANK,
    locator: { name: skill.name, directory, path },
    path,
    ...(skill.metadata !== undefined ? { metadata: skill.metadata } : {})
  }
}

/**
 * Build the full definition, including the body the model reads.
 * @param candidate - the winning candidate returned by `list()`.
 * @param skill - the matching catalog entry.
 * @param signal - optional cancellation; aborts the read.
 * @returns the definition, or undefined when the file vanished or no longer
 *   has readable frontmatter.
 */
async function definitionFor(candidate, skill, signal) {
  let raw
  try {
    raw = await readFile(candidate.locator.path, 'utf8')
  } catch {
    return undefined
  }
  if (signal?.aborted) return undefined
  const content = bodyOf(raw)
  if (content === undefined) return undefined
  return {
    name: skill.name,
    description: skill.description,
    ...(skill.whenToUse !== undefined ? { whenToUse: skill.whenToUse } : {}),
    invocation: skill.invocation,
    source: SOURCE,
    provider: name,
    resourceBase: { kind: 'directory', path: candidate.locator.directory },
    path: candidate.locator.path,
    ...(skill.metadata !== undefined ? { metadata: skill.metadata } : {}),
    content
  }
}

/**
 * Register the packaged Matt Pocock provider on `ctx.skills`. Cordis ties the
 * registration to this plugin's fiber: unloading the plugin unregisters the
 * provider and invalidates the registry's catalog cache.
 * @param ctx - the plugin context, with `skills` injected.
 */
function apply(ctx) {
  ctx.skills.registerProvider((control) => ({
    name,
    async list(options) {
      let catalog
      try {
        catalog = await loadCatalog()
      } catch (error) {
        ctx.logger?.warn(`dsh-mattpocock-skills: cannot read catalog.json: ${String(error)}`)
        return []
      }
      if (options?.signal?.aborted || control.signal.aborted) return []
      return catalog.skills.map(candidateFor)
    },
    async get(candidate, options) {
      const catalog = await loadCatalog()
      const skill = catalog.skills.find((entry) => entry.name === candidate.locator?.name)
      if (skill === undefined) return undefined
      return definitionFor(candidate, skill, options?.signal)
    }
  }))
}

export { apply, inject, name }
export default { apply, inject, name }
